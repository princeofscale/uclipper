"""Настройки «выбор из вариантов»: у каждого варианта есть название, значок и объяснение.

Раньше такие настройки переключались по кругу одной кнопкой — по подписи нельзя было понять, какие
вообще есть варианты. Теперь у каждой свой экран с описанием всех вариантов. Здесь только данные —
без aiogram, чтобы тексты, клавиатуры и хэндлеры брали правила из одного места.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Option:
    value: str
    icon: str
    label: str  # на кнопке выбора
    hint: str  # объяснение на экране выбора
    short: str  # как значение внутри кнопки настройки: «Кадр: 9:16 на весь экран»


@dataclass(frozen=True)
class Choice:
    field: str  # поле ClipSettings
    icon: str
    button: str  # слово на кнопке настройки: «Кадр», «Откуда»…
    title: str
    intro: str
    options: tuple[Option, ...]
    back: str = "screen:manual"  # куда вернуться после выбора

    def option(self, value: object) -> Option:
        key = str(getattr(value, "value", value))
        return next((option for option in self.options if option.value == key), self.options[0])

    def has(self, value: str) -> bool:
        return any(option.value == value for option in self.options)

    def caption(self, value: object) -> str:
        """Подпись кнопки настройки с текущим значением: «🖼 Кадр: 9:16 на весь экран»."""
        return f"{self.icon} {self.button}: {self.option(value).short}"


