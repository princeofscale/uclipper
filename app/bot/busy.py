"""Чем занят бот: почему сейчас нельзя начать нарезку (от этого красное меню, всплывающая подсказка и пояснение).

Бот ведёт один ролик за раз (`MAX_JOBS`): нарезка грузит процессор целиком, а сервер общий. Пока идёт одна,
остальные ролики не принимаются — ни ссылка, ни название, ни файл, ни «В тренде». Кнопки в меню при этом красные.
Telegram не умеет выключать inline-кнопки, поэтому «не нажимаются» значит «нажатие объясняет причину и ничего не делает».
"""
from __future__ import annotations

from dataclasses import dataclass
from enum import Enum


class Cause(Enum):
    MINE = "mine"  # идёт нарезка этого же человека (или бот досылает ему готовые клипы)
    OTHERS = "others"  # заняты чужой нарезкой: предел `MAX_JOBS` исчерпан
    DISK = "disk"  # на сервере мало места


@dataclass(frozen=True)
class Busy:
    """Состояние «сейчас нельзя»: причина и (для нарезки) что она делает."""

    cause: Cause
    progress: float = 0.0  # 0..100 идущей нарезки
    stage: str = ""  # что она делает сейчас: «Рендер клипа 3 из 8»
    job_id: str | None = None  # нарезка этого человека, которую ещё можно остановить (у досылаемой — `None`)
